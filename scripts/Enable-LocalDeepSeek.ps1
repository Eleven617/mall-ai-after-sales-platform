[CmdletBinding()]
param([switch]$Offline)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$override = Join-Path $root 'docker-compose.override.yml'
$marker = '# Generated by Enable-LocalDeepSeek.ps1; local interactive use, not release evidence.'
if (Test-Path -LiteralPath $override) {
    if (-not (Get-Content -LiteralPath $override -TotalCount 1).StartsWith($marker)) {
        throw 'An existing user Compose override was found; refusing to overwrite it.'
    }
}
$sha = (& git -C $root rev-parse HEAD).Trim()
if ($LASTEXITCODE -ne 0 -or $sha -notmatch '^[a-f0-9]{40}$') { throw 'Cannot identify source revision.' }
$mode = if ($Offline) { 'offline' } else { 'live' }
$auth = if ($Offline) { '0' } else { '1' }
$directory = Join-Path $root 'tmp/local-chat-usage'
[System.IO.Directory]::CreateDirectory($directory) | Out-Null
$ledger = Join-Path $directory 'ledger.jsonl'
if (-not (Test-Path -LiteralPath $ledger)) {
    $handle = [System.IO.File]::Open($ledger, [System.IO.FileMode]::CreateNew)
    $handle.Dispose()
}
# Reuse the budget across restarts. Never truncate or silently renew it.
# Existing guarded live transport is used, but local-chat IDs are NOT a
# release qualification, online evaluation batch, or immutable release lock.
$content = @"
$marker
services:
  mall-ai-service:
    build:
      args:
        RUNTIME_COMMIT: $sha
    labels:
      org.opencontainers.image.revision: $sha
    environment:
      MALL_RUNTIME_PROVIDER_MODE: $mode
      MALL_PROVIDER_LIVE_AUTH: '$auth'
      MALL_RUNTIME_COMMIT: $sha
      MALL_IMAGE_REVISION: $sha
      MALL_RELEASE_ID: local-chat
      MALL_RELEASE_BATCH_ID: local-chat
      MALL_RELEASE_LEDGER_PATH: /app/local-chat-usage/ledger.jsonl
      MALL_RELEASE_MAX_PROVIDER_HTTP_ATTEMPTS: '600'
      MALL_RELEASE_MAX_TOTAL_TOKENS: '1600000'
      MALL_RELEASE_RESERVE_TOKENS: '12000'
    volumes:
      - ./tmp/local-chat-usage:/app/local-chat-usage
    ports: !override
      - '127.0.0.1:8000:8000'
  mall-ai-web:
    ports: !override
      - '127.0.0.1:5173:80'
"@
[System.IO.File]::WriteAllText($override, $content, [System.Text.UTF8Encoding]::new($false))
Write-Host "Local chat mode: $mode. Persistent budget: 600 HTTP attempts / 1600000 tokens; no automatic reset."
Write-Host 'No Provider request has been made. Existing key remains private. Formal runners using only the base Compose file are unchanged.'
